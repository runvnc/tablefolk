import { chromium } from 'playwright-core';
import fs from 'fs';
const b = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = b.contexts()[0].pages().find(p => /8000/.test(p.url()));
const out = await page.evaluate(async (H) => { const process_eye = (p, d) => new BABYLON.Vector3(p.x + d.x * .3, H, p.z + d.z * .3 + (H > 2 ? 4 : 0));
  const sc = state.scene, cam = sc.activeCamera, g = state.characters[0];
  const p = g.root.position, d = new BABYLON.Vector3(g.dir?.x || 0, 0, g.dir?.z || 1).normalize();
  const save = { a: cam.alpha, b: cam.beta, r: cam.radius, t: cam.target.clone(), fov: cam.fov, minZ: cam.minZ, lr: cam.lowerRadiusLimit, lb: cam.lowerBetaLimit, ub: cam.upperBetaLimit, la: cam.lowerAlphaLimit, ua: cam.upperAlphaLimit };
  cam.lowerRadiusLimit = null; cam.lowerBetaLimit = null; cam.upperBetaLimit = null; cam.lowerAlphaLimit = null; cam.upperAlphaLimit = null;
  const eye = process_eye(p, d);
  cam.setTarget(eye.add(d.scale(4)).add(new BABYLON.Vector3(0, -.55, 0))); cam.setPosition(eye); cam.fov = 1.15; cam.minZ = .05;
  state.engine.beginFrame(); sc.render(); state.engine.endFrame();
  const cv = state.engine.getRenderingCanvas();
  const url = cv.toDataURL('image/jpeg', .85);
  Object.assign(cam, { lowerRadiusLimit: save.lr, lowerBetaLimit: save.lb, upperBetaLimit: save.ub, lowerAlphaLimit: save.la, upperAlphaLimit: save.ua, fov: save.fov, minZ: save.minZ });
  cam.setTarget(save.t); cam.alpha = save.a; cam.beta = save.b; cam.radius = save.r;
  return url;
}, +(process.argv[2] || .85));
fs.writeFileSync('/tmp/claude-1000/-mnt-files-geebr-world/bde8bf29-8007-4375-b49f-eeda1155bc3c/scratchpad/eye.jpg', Buffer.from(out.split(',')[1], 'base64'));
await b.close().catch(() => {});
