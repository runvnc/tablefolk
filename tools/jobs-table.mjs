// Writes server/jobs-table.js from jobs/*/job.json: what the world builder's
// checks (server/worldgen-core.js livingWorld) need to know about each
// built-in job without fetching files (the Cloudflare Worker has none).
//   node tools/jobs-table.mjs          (run after editing a job.json)
import fs from 'fs';
import path from 'path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = {};
for (const id of fs.readdirSync(path.join(root, 'jobs')).sort()) {
  const f = path.join(root, 'jobs', id, 'job.json'); if (!fs.existsSync(f)) continue;
  const j = JSON.parse(fs.readFileSync(f, 'utf8'));
  const steps = j.steps || [];
  out[j.id] = {
    match: j.match || '',
    workplace: j.workplace || [],
    fights: !!j.fights,
    sells: steps.some(s => s.sell || s.serve),
    makes: [...new Set(steps.map(s => s.make).filter(Boolean))],
    gathers: [...new Set(steps.map(s => s.gather).filter(x => typeof x === 'string'))],
    stores: steps.some(s => s.store),
    patrols: steps.some(s => s.patrol),
  };
}
const body = `// Generated by tools/jobs-table.mjs from jobs/*/job.json: do not edit by hand.\nexport const JOBS = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'server/jobs-table.js'), body);
console.log('server/jobs-table.js:', Object.keys(out).length, 'jobs');
